package tech.ixor.kotlox.tools

import java.io.File
import kotlin.system.exitProcess

private const val EX_USAGE = 64

/**
 * One node type of the syntax tree, e.g. `Binary : left: Expr, operator: Token, right: Expr`.
 */
private data class AstType(val className: String, val fields: List<String>) {
    companion object {
        fun parse(definition: String): AstType {
            val (className, fieldList) = definition.split(":", limit = 2).map { it.trim() }
            return AstType(className, fieldList.split(", "))
        }
    }
}

//> Generating Methods
private fun StringBuilder.defineVisitor(baseName: String, types: List<AstType>) {
    appendLine("    public interface Visitor<R> {")
    for (type in types) {
        appendLine("        public fun visit${type.className}$baseName(${baseName.lowercase()}: ${type.className}): R")
    }
    appendLine("    }")
}

private fun StringBuilder.defineType(baseName: String, type: AstType) {
    val marker = "${baseName.lowercase()}-${type.className.lowercase()}"

    appendLine()
    appendLine("    //> $marker")
    appendLine("    public data class ${type.className}(")
    //> Fields
    for (field in type.fields) {
        appendLine("        val $field,")
    }
    //< Fields
    appendLine("    ) : $baseName() {")
    //> Visitor Pattern
    appendLine(
        "        override fun <R> accept(visitor: Visitor<R>): R = visitor.visit${type.className}$baseName(this)",
    )
    //< Visitor Pattern
    appendLine("    }")
    appendLine("    //< $marker")
}

private fun defineAst(outputDir: String, baseName: String, types: List<String>) {
    val astTypes = types.map(AstType::parse)
    val source = buildString {
        appendLine("// Generated by tools/generate-ast. Do not edit by hand.")
        appendLine("package tech.ixor.kotlox.ast")
        appendLine()
        appendLine("import tech.ixor.kotlox.token.Token")
        appendLine()
        appendLine("public sealed class $baseName {")
        defineVisitor(baseName, astTypes)
        appendLine()
        appendLine("    public abstract fun <R> accept(visitor: Visitor<R>): R")
        astTypes.forEach { defineType(baseName, it) }
        appendLine("}")
    }
    File(outputDir, "$baseName.kt").writeText(source)
}
//< Generating Methods

fun main(args: Array<String>) {
    if (args.size != 1) {
        System.err.println("Usage: generate-ast <output directory>")
        exitProcess(EX_USAGE)
    }
    val outputDir = args[0]

    defineAst(
        outputDir,
        "Expr",
        listOf(
            "Binary   : left: Expr, operator: Token, right: Expr",
            "Grouping : expression: Expr",
            "Literal  : value: Any?",
            "Unary    : operator: Token, right: Expr",
        ),
    )
}
